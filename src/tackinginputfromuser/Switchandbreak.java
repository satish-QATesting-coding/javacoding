package tackinginputfromuser;

public class Switchandbreak {

	public static void main(String[] args) {

		char grade= 'C';
		
		switch(grade) 
		{
		case 'A':
		 System.out.println("EXCELENT");
		  break;
		case 'B': 
			System.out.println("GOOD");
			break;
		case 'C': 
			System.out.println("AVG");
			break;
		case 'D': 
			System.out.println("BELOW AVG");
		break;
		
		
		
		
		}
	}

}
